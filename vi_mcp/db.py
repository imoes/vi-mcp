"""Database access: SQLite (default, standard library) or PostgreSQL (optional, psycopg 3).

The code base writes SQLite SQL against the `sqlite3` interface (execute, executemany, executescript, commit, cursors with fetchone,
fetchall, rowcount). `connect()` returns a plain `sqlite3.Connection` for a file path and a `PgConnection` for a `postgresql://` URL.
`PgConnection` offers the same interface and translates the few SQLite idioms the code uses, statement by statement:

| SQLite | PostgreSQL |
|---|---|
| `?` placeholders | `%s` (a literal `%` becomes `%%`) |
| `INSERT OR IGNORE` | `INSERT … ON CONFLICT DO NOTHING` |
| `INSERT OR REPLACE` | `INSERT … ON CONFLICT (primary key) DO UPDATE SET …` (key read from the catalogue) |
| `LIKE` (case-insensitive for ASCII) | `ILIKE` |
| `x IS ?` / `x IS NOT ?` | `IS NOT DISTINCT FROM` / `IS DISTINCT FROM` |
| `group_concat(x, sep)` | `string_agg(x, sep)` |
| `INTEGER`, `REAL`, `BLOB` | `BIGINT`, `DOUBLE PRECISION`, `BYTEA` |
| `json_extract`, `json_array_length`, `instr` | SQL functions of the same name in the schema (installed on connect) |
| FTS5 table `objekt_fts` | table with a generated `tsvector` column and a GIN index (search: `memory.recall`) |
| `PRAGMA table_info(t)` | `information_schema.columns` |
| other `PRAGMA` (journal, checkpoint, busy timeout) | no-op |
| `sqlite_master … type = 'table' AND name = ` | `information_schema.tables` |
| `rowid` | `ctid` |

Transactions behave like `sqlite3`: a transaction begins with the first writing statement and ends with `commit()`; reads outside it
run in autocommit and hold nothing open. A failed statement in PostgreSQL aborts the whole transaction — so every statement inside a
transaction runs in a savepoint, and a caught `IntegrityError` leaves the transaction usable as in SQLite. Errors are raised as
`sqlite3.IntegrityError` / `sqlite3.OperationalError`, so existing `except sqlite3.…` clauses keep working.
"""
from __future__ import annotations

import re
import sqlite3
import threading
from typing import Any, Iterable

PG_PREFIXES = ("postgresql://", "postgres://")


def is_url(target: Any) -> bool:
    return str(target).startswith(PG_PREFIXES)


def connect(target: Any, *, schema: str | None = None, autocommit: bool = False, **sqlite_kw) -> Any:
    """A file path → sqlite3.Connection (sqlite_kw passed on); a postgresql:// URL → PgConnection in `schema`
    (created if missing; None = the URL's search_path). autocommit=True corresponds to sqlite3's isolation_level=None."""
    if is_url(target):
        return PgConnection(str(target), schema=schema, autocommit=autocommit)
    if autocommit:
        sqlite_kw.setdefault("isolation_level", None)
    return sqlite3.connect(str(target), **sqlite_kw)


def connect_readonly(target: Any) -> Any:
    """For tools that only look (vi-mcp instance, embed compare): SQLite with mode=ro, PostgreSQL with read-only transactions."""
    if is_url(target):
        con = PgConnection(str(target))
        con._con.execute("SET default_transaction_read_only = on")
        return con
    return sqlite3.connect(f"file:{target}?mode=ro", uri=True)


def backend(con: Any) -> str:
    return "postgres" if isinstance(con, PgConnection) else "sqlite"


def redact(target: Any) -> str:
    """For logs: a URL without its password (postgresql://user:secret@host → postgresql://user:***@host)."""
    return re.sub(r"(://[^:/@]+:)[^@]*@", r"\1***@", str(target))


# ---------------------------------------------------------------- translation (pure)

_LITERAL = re.compile(r"'(?:[^']|'')*'")
_FTS5 = re.compile(r"CREATE\s+VIRTUAL\s+TABLE\s+(IF\s+NOT\s+EXISTS\s+)?(\w+)\s+USING\s+fts5\s*\(([^)]*)\)", re.I)
_INSERT_OR = re.compile(r"^\s*INSERT\s+OR\s+(IGNORE|REPLACE)\s+INTO\s+(\w+)\s*(\(([^)]*)\))?", re.I)
_REPLACE_INTO = re.compile(r"^\s*REPLACE\s+INTO\s+(\w+)\s*(\(([^)]*)\))?", re.I)
_PRAGMA_INFO = re.compile(r"^\s*PRAGMA\s+table_info\s*\(\s*['\"]?(\w+)['\"]?\s*\)\s*;?\s*$", re.I)
_PRAGMA = re.compile(r"^\s*PRAGMA\b", re.I)
_GROUP_CONCAT = re.compile(r"\bgroup_concat\s*\(\s*(DISTINCT\s+)?([^(),]+?)\s*(?:,\s*([^()]+?)\s*)?\)", re.I)


def _outside_literals(sql: str, fn) -> str:
    """Apply fn to every part of sql that is not inside a '…' literal."""
    out, pos = [], 0
    for m in _LITERAL.finditer(sql):
        out.append(fn(sql[pos:m.start()]))
        out.append(m.group(0))
        pos = m.end()
    out.append(fn(sql[pos:]))
    return "".join(out)


def _code(part: str) -> str:
    part = re.sub(r"\bNOT\s+LIKE\b", "NOT ILIKE", part, flags=re.I)
    part = re.sub(r"(?<!NOT )(?<!I)\bLIKE\b", "ILIKE", part, flags=re.I)
    part = re.sub(r"\bIS\s+NOT\s+\?", "IS DISTINCT FROM ?", part, flags=re.I)
    part = re.sub(r"\bIS\s+\?", "IS NOT DISTINCT FROM ?", part, flags=re.I)
    part = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", part, flags=re.I)  # SQLite: rowid alias
    part = re.sub(r"\bINTEGER\b(?! GENERATED)", "BIGINT", part, flags=re.I)
    part = re.sub(r"\bREAL\b", "DOUBLE PRECISION", part, flags=re.I)
    part = re.sub(r"\bBLOB\b", "BYTEA", part, flags=re.I)
    part = re.sub(r"\browid\b", "ctid", part, flags=re.I)
    part = re.sub(r"\bCREATE\s+INDEX\s+temp\.", "CREATE INDEX ", part, flags=re.I)  # an index name takes no schema in PostgreSQL
    part = re.sub(r"\btemp\.", "pg_temp.", part, flags=re.I)
    return part.replace("?", "%s")


def translate(sql: str, primary_key=None, columns=None) -> list[str]:
    """SQLite SQL → PostgreSQL statements (usually one). primary_key(table) and columns(table) are only asked for INSERT OR REPLACE.
    Pure apart from those two callbacks."""
    s = sql.strip().rstrip(";").strip()
    m = _FTS5.match(s)
    if m:
        name = m.group(2)
        cols = [c.split()[0] for c in m.group(3).split(",")]
        text_cols = [c for c in cols if c != cols[0]] or cols
        doc = " || ' ' || ".join(f"coalesce({c}, '')" for c in text_cols)
        return [f"CREATE TABLE IF NOT EXISTS {name} ({', '.join(f'{c} TEXT' for c in cols)}, "
                f"tsv tsvector GENERATED ALWAYS AS (to_tsvector('simple', {doc})) STORED)",
                f"CREATE INDEX IF NOT EXISTS {name}_tsv ON {name} USING gin (tsv)",
                f"CREATE INDEX IF NOT EXISTS {name}_{cols[0]} ON {name} ({cols[0]})"]
    m = _PRAGMA_INFO.match(s)
    if m:
        return ["SELECT ordinal_position - 1, column_name, data_type, CASE WHEN is_nullable = 'NO' THEN 1 ELSE 0 END, column_default, 0 "
                f"FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = '{m.group(1).lower()}' ORDER BY ordinal_position"]
    if _PRAGMA.match(s):
        return []  # journal mode, busy timeout, checkpoints: PostgreSQL handles them itself
    conflict = ""
    m = _INSERT_OR.match(s) or _REPLACE_INTO.match(s)
    if m:
        is_or = m.re is _INSERT_OR
        mode = m.group(1).upper() if is_or else "REPLACE"
        table = m.group(2) if is_or else m.group(1)
        col_text = m.group(4) if is_or else m.group(3)
        s = f"INSERT INTO {table}" + (f" ({col_text})" if col_text else "") + s[m.end():]
        if mode == "IGNORE":
            conflict = " ON CONFLICT DO NOTHING"
        else:
            key = primary_key(table) if primary_key else []
            cols = [c.strip() for c in col_text.split(",")] if col_text else (columns(table) if columns else [])
            rest = [c for c in cols if c not in key]
            if not key:
                raise sqlite3.OperationalError(f"INSERT OR REPLACE into {table}: table has no primary key")
            conflict = f" ON CONFLICT ({', '.join(key)}) " + (f"DO UPDATE SET {', '.join(f'{c} = EXCLUDED.{c}' for c in rest)}" if rest else "DO NOTHING")
    s = re.sub(r"FROM\s+sqlite_master\s+WHERE\s+type\s*=\s*'table'\s+AND\s+name\s*=",
               "FROM information_schema.tables WHERE table_schema = current_schema() AND table_name =", s, flags=re.I)
    s = s.replace("%", "%%")
    s = _GROUP_CONCAT.sub(lambda g: f"string_agg({g.group(1) or ''}{g.group(2)}, {g.group(3) or chr(39) + ',' + chr(39)})", s)
    s = _outside_literals(s, _code)
    return [s + conflict]


def split_script(script: str) -> list[str]:
    """executescript: statements separated by ';' outside literals."""
    out, cur, pos = [], [], 0
    masked = _LITERAL.sub(lambda m: "\0" * len(m.group(0)), script)
    for i, ch in enumerate(masked):
        if ch == ";":
            out.append(script[pos:i])
            pos = i + 1
    out.append(script[pos:])
    return [x.strip() for x in out if x.strip()]


# ---------------------------------------------------------------- PostgreSQL connection

FUNCTIONS = r"""
CREATE OR REPLACE FUNCTION json_extract(doc text, path text) RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE AS
  $f$ SELECT CASE WHEN $2 = '$' THEN $1 ELSE ($1::jsonb) #>> string_to_array(substr($2, 3), '.') END $f$;
CREATE OR REPLACE FUNCTION json_array_length(doc text) RETURNS integer LANGUAGE sql IMMUTABLE PARALLEL SAFE AS
  $f$ SELECT jsonb_array_length($1::jsonb) $f$;
CREATE OR REPLACE FUNCTION instr(a text, b text) RETURNS integer LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $f$ SELECT strpos($1, $2) $f$;
CREATE OR REPLACE FUNCTION vi_sum_bool(s bigint, x boolean) RETURNS bigint LANGUAGE sql IMMUTABLE PARALLEL SAFE AS
  $f$ SELECT CASE WHEN $2 IS NULL THEN $1 ELSE COALESCE($1, 0) + CASE WHEN $2 THEN 1 ELSE 0 END END $f$;
CREATE OR REPLACE AGGREGATE sum(boolean) (SFUNC = vi_sum_bool, STYPE = bigint)
"""
_WRITE = re.compile(r"^\s*(INSERT|UPDATE|DELETE|REPLACE|CREATE|DROP|ALTER)\b", re.I)
_TX = re.compile(r"^\s*(BEGIN|COMMIT|END|ROLLBACK)\b", re.I)


def _error(exc: Exception) -> Exception:
    import psycopg
    cls = sqlite3.IntegrityError if isinstance(exc, psycopg.errors.IntegrityError) else sqlite3.OperationalError
    e = cls(str(exc).strip())
    e.__cause__ = exc
    return e


class PgCursor:
    """The part of sqlite3.Cursor the code uses."""

    def __init__(self, cur=None, rows: list | None = None):
        self._cur, self._rows = cur, rows
        self.rowcount = cur.rowcount if cur is not None else -1

    @property
    def description(self):
        return self._cur.description if self._cur is not None else None

    def fetchone(self):
        if self._rows is not None:
            return self._rows.pop(0) if self._rows else None
        return self._cur.fetchone() if self._cur is not None and self._cur.description is not None else None

    def fetchall(self) -> list:
        if self._rows is not None:
            rows, self._rows = self._rows, []
            return rows
        return self._cur.fetchall() if self._cur is not None and self._cur.description is not None else []

    def fetchmany(self, size: int = 1) -> list:
        if self._rows is not None:
            rows, self._rows = self._rows[:size], self._rows[size:]
            return rows
        return self._cur.fetchmany(size) if self._cur is not None and self._cur.description is not None else []

    def __iter__(self):
        return iter(self.fetchall())

    def close(self) -> None:
        if self._cur is not None:
            self._cur.close()


class PgConnection:
    """sqlite3-like connection to PostgreSQL. Thread-safe like a sqlite3 connection with check_same_thread=False: one statement at a time."""

    def __init__(self, url: str, schema: str | None = None, autocommit: bool = False):
        try:
            import psycopg
        except ImportError as exc:  # optional dependency: name the package
            raise RuntimeError("PostgreSQL needs psycopg 3: apt install python3-psycopg · dnf install python3-psycopg3 · pip install psycopg") from exc
        from psycopg.types.numeric import FloatLoader
        self.url, self.autocommit_mode = url, autocommit
        self._con = psycopg.connect(url, autocommit=True)
        self._con.adapters.register_loader("numeric", FloatLoader)  # SUM/AVG over integers: float as in SQLite, not Decimal
        self._lock = threading.RLock()
        self._tx = False
        self._sp = 0
        self._keys: dict[str, list[str]] = {}
        self._cols: dict[str, list[str]] = {}
        if schema:
            if not re.fullmatch(r"[a-z_][a-z0-9_]{0,62}", schema):
                raise ValueError(f"schema name {schema!r}: only a-z, 0-9, _")
            self._con.execute(f"CREATE SCHEMA IF NOT EXISTS {schema}")
            self._con.execute(f"SET search_path TO {schema}")
        self.schema = self._con.execute("SELECT current_schema()").fetchone()[0]
        if self.schema is None:  # the URL names a schema (options=-csearch_path=NAME) that does not exist yet: create it
            first = self._con.execute("SHOW search_path").fetchone()[0].split(",")[0].strip().strip('"')
            if not re.fullmatch(r"[a-z_][a-z0-9_]{0,62}", first):
                raise ValueError(f"search_path {first!r}: only a-z, 0-9, _")
            self._con.execute(f"CREATE SCHEMA IF NOT EXISTS {first}")
            self.schema = self._con.execute("SELECT current_schema()").fetchone()[0]
        with self._con.transaction():  # concurrent CREATE OR REPLACE FUNCTION collides without the lock
            self._con.execute("SELECT pg_advisory_xact_lock(4711)")
            for stmt in split_script(FUNCTIONS):
                self._con.execute(stmt)

    # ---- catalogue (for INSERT OR REPLACE)
    def _primary_key(self, table: str) -> list[str]:
        if table not in self._keys:
            self._keys[table] = [r[0] for r in self._con.execute(
                "SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey) "
                "WHERE i.indrelid = (quote_ident(current_schema()) || '.' || quote_ident(%s))::regclass AND i.indisprimary "
                "ORDER BY array_position(i.indkey, a.attnum)", (table.lower(),)).fetchall()]
        return self._keys[table]

    def _columns(self, table: str) -> list[str]:
        if table not in self._cols:
            self._cols[table] = [r[0] for r in self._con.execute(
                "SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = %s "
                "AND is_generated = 'NEVER' ORDER BY ordinal_position", (table.lower(),)).fetchall()]
        return self._cols[table]

    # ---- transactions
    @property
    def in_transaction(self) -> bool:
        return self._tx

    def _begin(self) -> None:
        if not self._tx:
            self._con.execute("BEGIN")
            self._tx = True

    def commit(self) -> None:
        with self._lock:
            if self._tx:
                self._tx = False
                self._con.execute("COMMIT")

    def rollback(self) -> None:
        with self._lock:
            if self._tx:
                self._tx = False
                self._con.execute("ROLLBACK")

    def close(self) -> None:
        with self._lock:
            try:
                self.commit()
            finally:
                self._con.close()

    # ---- statements
    def _run(self, stmts: list[str], params: Iterable | None, many: bool = False):
        import psycopg
        if self._tx:
            self._sp += 1
            sp = f"vi_sp{self._sp}"
            self._con.execute(f"SAVEPOINT {sp}")
        else:
            sp = None
        try:
            cur = None
            for stmt in stmts:
                cur = self._con.cursor()
                if many:
                    cur.executemany(stmt, [tuple(p) for p in params])
                else:
                    cur.execute(stmt, tuple(params or ()))
            if sp:
                self._con.execute(f"RELEASE SAVEPOINT {sp}")
            return cur
        except psycopg.Error as exc:
            if sp:
                self._con.execute(f"ROLLBACK TO SAVEPOINT {sp}")
                self._con.execute(f"RELEASE SAVEPOINT {sp}")
            raise _error(exc) from exc
        finally:
            if sp:
                self._sp -= 1

    def _prepare(self, sql: str) -> list[str]:
        if re.match(r"^\s*(INSERT\s+OR\s+REPLACE|REPLACE)\b", sql, re.I):
            return translate(sql, self._primary_key, self._columns)
        return translate(sql)

    def execute(self, sql: str, params: Iterable | None = ()) -> PgCursor:
        with self._lock:
            t = _TX.match(sql)
            if t:
                word = t.group(1).upper()
                if word == "BEGIN":
                    self._begin()
                elif word == "ROLLBACK":
                    self.rollback()
                else:
                    self.commit()
                return PgCursor(rows=[])
            stmts = self._prepare(sql)
            if not stmts:
                return PgCursor(rows=[])
            if _WRITE.match(sql) and not self.autocommit_mode:
                self._begin()
            if re.match(r"^\s*(CREATE|DROP|ALTER)\b", sql, re.I):
                self._keys.clear()
                self._cols.clear()
            return PgCursor(self._run(stmts, params))

    def executemany(self, sql: str, seq: Iterable[Iterable]) -> PgCursor:
        with self._lock:
            seq = list(seq)
            if not seq:
                return PgCursor(rows=[])
            stmts = self._prepare(sql)
            if _WRITE.match(sql) and not self.autocommit_mode:
                self._begin()
            return PgCursor(self._run(stmts, seq, many=True))

    def executescript(self, script: str) -> PgCursor:
        with self._lock:
            self.commit()  # like sqlite3: a script commits what is pending first
            for stmt in split_script(script):
                self.execute(stmt)
            self.commit()
            return PgCursor(rows=[])

    def cursor(self) -> "PgConnection":
        return self
