"""0.50.0: optional PostgreSQL — the SQL translation (pure, always) and, with VI_MCP_TEST_PG=postgresql://…, the real database:
transactions like sqlite3, migration of memory, archive and a network logbook, the configure switch that refuses an empty target."""
import json
import os
import sqlite3
import uuid

import pytest

from vi_mcp import config, configure, db, logbook as lb
from vi_mcp import memory as g

PG = os.environ.get("VI_MCP_TEST_PG")
needs_pg = pytest.mark.skipif(not PG, reason="needs VI_MCP_TEST_PG=postgresql://… (a throw-away database)")


def test_translation_of_the_sqlite_idioms():
    pk = {"objekt": ["id"], "tag": ["objekt_id", "tag"]}.get
    t = lambda q: db.translate(q, pk, None)[0]
    assert t("SELECT id FROM tag WHERE tag LIKE 'tool:%' AND x NOT LIKE ? AND n IS ? AND m IS NOT ?") == \
        "SELECT id FROM tag WHERE tag ILIKE 'tool:%%' AND x NOT ILIKE %s AND n IS NOT DISTINCT FROM %s AND m IS DISTINCT FROM %s"
    assert t("INSERT OR IGNORE INTO tag (objekt_id, tag) VALUES (?, ?)") == "INSERT INTO tag (objekt_id, tag) VALUES (%s, %s) ON CONFLICT DO NOTHING"
    assert t("INSERT OR REPLACE INTO objekt (id, art) VALUES (?,?)") == \
        "INSERT INTO objekt (id, art) VALUES (%s,%s) ON CONFLICT (id) DO UPDATE SET art = EXCLUDED.art"
    assert t("INSERT OR REPLACE INTO tag (objekt_id, tag) VALUES (?,?)").endswith("ON CONFLICT (objekt_id, tag) DO NOTHING")
    assert t("SELECT group_concat(tag, ' '), group_concat(DISTINCT i) FROM t") == "SELECT string_agg(tag, ' '), string_agg(DISTINCT i, ',') FROM t"
    assert t("CREATE TABLE x (v INTEGER PRIMARY KEY, a INTEGER, b REAL, c BLOB)") == \
        "CREATE TABLE x (v BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, a BIGINT, b DOUBLE PRECISION, c BYTEA)"
    assert t("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'p2p_inhalt'") == \
        "SELECT 1 FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = 'p2p_inhalt'"
    assert t("SELECT 'it''s ? 50%', ? ORDER BY zeit, rowid") == "SELECT 'it''s ? 50%%', %s ORDER BY zeit, ctid"  # literals untouched
    assert t("DROP TABLE IF EXISTS temp.b") == "DROP TABLE IF EXISTS pg_temp.b" and t("CREATE INDEX temp.b_a ON b (a)") == "CREATE INDEX b_a ON b (a)"
    fts = db.translate("CREATE VIRTUAL TABLE IF NOT EXISTS objekt_fts USING fts5(id UNINDEXED, text)")
    assert "tsvector GENERATED ALWAYS AS (to_tsvector('simple'" in fts[0] and "USING gin (tsv)" in fts[1]
    assert db.translate("PRAGMA journal_mode=WAL") == [] and "information_schema.columns" in db.translate("PRAGMA table_info(peer)")[0]
    with pytest.raises(sqlite3.OperationalError, match="no primary key"):
        db.translate("INSERT OR REPLACE INTO log (a) VALUES (?)", lambda _t: [], None)


def test_script_split_and_redaction():
    assert db.split_script("CREATE TABLE a (x TEXT DEFAULT ';');\n CREATE INDEX i ON a(x);\n") == ["CREATE TABLE a (x TEXT DEFAULT ';')", "CREATE INDEX i ON a(x)"]
    assert db.redact("postgresql://vi:secret@db.example/vi") == "postgresql://vi:***@db.example/vi"
    assert db.backend(sqlite3.connect(":memory:")) == "sqlite"


def test_config_keeps_a_url_intact(tmp_path, monkeypatch):
    p = tmp_path / "c.json"
    p.write_text(json.dumps({"db": "postgresql://vi-mcp@/vi?host=/var/run/postgresql"}))
    monkeypatch.setenv("VI_MCP_CONFIG", str(p))
    assert config.load().db == "postgresql://vi-mcp@/vi?host=/var/run/postgresql"
    p.write_text(json.dumps({"db": "~/x/vi.db"}))
    assert str(config.load().db).endswith("/x/vi.db") and "~" not in str(config.load().db)


def test_configure_checks_the_url():
    assert configure.validate({"db": "postgresql://vi:pw@h/vi"}) and "no password" in configure.validate({"db": "postgresql://vi:pw@h/vi"})["db"]
    assert configure.validate({"db": "mysql://h/vi"})
    assert configure.validate({"db": "postgresql://vi@h/vi"}) == {} and configure.validate({"db": ""}) == {}


def _url(schema):
    return f"{PG}{'&' if '?' in PG else '?'}options=-csearch_path%3D{schema}"


def _schema():
    return "x_" + uuid.uuid4().hex[:16]


@needs_pg
def test_transactions_behave_like_sqlite3():
    c = db.connect(_url(_schema()))
    c.executescript("CREATE TABLE t (k TEXT PRIMARY KEY, v INTEGER)")
    c.execute("INSERT INTO t VALUES (?, ?)", ("a", 1))
    with pytest.raises(sqlite3.IntegrityError):
        c.execute("INSERT INTO t VALUES (?, ?)", ("a", 2))
    c.execute("INSERT INTO t VALUES (?, ?)", ("b", 2))  # the transaction survived the caught error (savepoint)
    c.commit()
    c.execute("INSERT INTO t VALUES (?, ?)", ("c", 3))
    c.rollback()
    assert c.execute("SELECT k, v FROM t ORDER BY k").fetchall() == [("a", 1), ("b", 2)]
    assert c.execute("SELECT SUM(v > 1), SUM(v) FROM t").fetchone() == (1, 3.0)  # boolean sum and float like SQLite
    assert c.execute("SELECT json_extract(?, '$.a.b'), instr('ab:c', ':')", ('{"a": {"b": "x"}}',)).fetchone() == ("x", 3)
    c.close()


def _sqlite_memory(path):
    open_sqlite = getattr(g.open_db, "original", g.open_db)
    open_sqlite(path)
    from vi_mcp import archive
    k = g.new_object("erkenntnis", "borg needs BORG_PASSCOMMAND for unattended runs", ["tool:borg", "thema:backup"], {"quelle": "test", "inhalt": "borg create --stats repo::{now} /etc"}, instance="a")
    old = g.new_object("erkenntnis", "an old note about rsync", ["tool:rsync"], {"quelle": "test"}, instance="a")
    archive.store_in_archive(old, "test")
    g.close_db()
    return k


@needs_pg
def test_migrate_memory_and_archive(tmp_path, monkeypatch):
    k = _sqlite_memory(tmp_path / "vi.db")
    from vi_mcp import db_migrate
    url = _url(_schema())
    report = db_migrate.migrate_memory(tmp_path / "vi.db", url, say=lambda *_: None)
    assert report["objekt"][0] == report["objekt"][1] >= 2 and all(a == b for a, b in report.values())
    assert any(t.startswith("lager.") for t in report)
    g.open_db(url)
    try:
        assert g.backend() == "postgres"
        hits = [o.id for _s, o, _g in g.recall("BORG_PASSCOMMAND", viewer=None)]
        assert hits == [k.id] and "borg create --stats" in g.load(k.id).data["inhalt"]  # full text and content came along
        assert [o.id for _s, o, _g in g.recall("tool:borg", viewer=None)] == [k.id]
        new = g.new_object("erkenntnis", "written after the move", ["thema:x"], {"quelle": "t"}, instance="a")
        assert g.load(new.id).text == "written after the move"
    finally:
        g.close_db()
    with pytest.raises(ValueError, match="already holds rows"):
        db_migrate.copy(tmp_path / "vi.db", url)


@needs_pg
def test_migrate_a_network_logbook(tmp_path):
    """A logbook file written by an older server (SQLite, built in a child process without the PostgreSQL redirect of the tests)
    moves into its own schema; the chain continues there."""
    import subprocess
    import sys
    from vi_mcp import db_migrate
    seed, src = tmp_path / "seed", tmp_path / "netz.db"
    lb.generate_keys(seed)
    code = ("import sys; from pathlib import Path; from vi_mcp import logbook as lb; "
            "b = lb.Logbook(Path(sys.argv[1]), Path(sys.argv[2]), []); b.attach('adresse', {'adresse': 'https://a.example'})")
    env = {k: v for k, v in os.environ.items() if k != "VI_MCP_TEST_PG"}
    out = subprocess.run([sys.executable, "-c", code, str(src), str(seed)], capture_output=True, text=True, env=env)
    assert out.returncode == 0, out.stderr
    schema = lb.schema_for("welt-" + uuid.uuid4().hex[:6])
    report = db_migrate.copy(src, PG, schema=schema, say=lambda *_: None)
    assert report["eintrag"] == (1, 1) and all(a == b for a, b in report.values())
    moved = lb.Logbook(PG, seed, [], schema=schema)
    assert moved.db.execute("SELECT COUNT(*) FROM eintrag").fetchone()[0] == 1
    moved.attach("adresse", {"adresse": "https://b.example"})  # the chain continues on PostgreSQL
    assert moved.db.execute("SELECT MAX(seq) FROM eintrag").fetchone()[0] == 2


@needs_pg
def test_configure_refuses_an_empty_target_and_takes_a_migrated_one(tmp_path, monkeypatch):
    from vi_mcp import db_migrate, net_cli, setup
    cfgp = tmp_path / "config.json"
    _sqlite_memory(tmp_path / "vi.db")
    cfgp.write_text(json.dumps({"db": str(tmp_path / "vi.db"), "instanzen": {}}))
    monkeypatch.setenv("VI_MCP_CONFIG", str(cfgp))
    monkeypatch.setattr(configure, "STATE", tmp_path / "configure.json")
    monkeypatch.setattr(setup, "_restart", lambda: None)
    monkeypatch.setattr(net_cli, "main", lambda argv: 0)
    url = _url(_schema())
    with pytest.raises(ValueError, match="run vi-mcp db migrate"):
        configure.apply({"db": url})
    db_migrate.migrate_memory(tmp_path / "vi.db", url, say=lambda *_: None)
    assert "database → PostgreSQL" in configure.apply({"db": url})
    assert json.loads(cfgp.read_text())["db"] == url and config.load().db == url
    assert "objects" in db_migrate.status() and "PostgreSQL" in db_migrate.status()
